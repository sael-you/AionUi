/** The AionUi locale for a Chrome UI language ("de", "pt-BR", "zh-TW", …); English otherwise. */
export const localeFor = (uiLanguage: string): Locale => {
  const lang = uiLanguage.replace('_', '-');
  const exact = LOCALES.find((locale) => locale.toLowerCase() === lang.toLowerCase());
  if (exact) return exact;
  if (/^zh-(tw|hk|mo|hant)/i.test(lang)) return 'zh-TW';
  const base = lang.split('-')[0].toLowerCase();
  return LOCALES.find((locale) => locale.split('-')[0] === base) ?? 'en-US';
};

export const translate = (locale: Locale, key: MessageKey, vars: Record<string, string> = {}): string =>
  (MESSAGES[locale][key] ?? MESSAGES['en-US'][key]).replace(/\{(\w+)\}/g, (_, name: string) => vars[name] ?? '');
